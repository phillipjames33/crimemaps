  static Incident _incident({
    required String id,
    required String title,
    required IncidentCategory category,
    required IncidentSeverity severity,
    required String address,
    required String placeName,
    required String placeType,
    required double lat,
    required double lng,
    required String citySlug,
    required String cityName,
    required String stateCode,
    required int hoursAgo,
    required String sourceAgency,
    String? offenderName,
    List<String>? charges,
    String? bookingAgency,
  }) {
    final occurredAt = _anchor.subtract(Duration(hours: hoursAgo));
    final hasOffender = offenderName != null && charges != null;
    final expiry = hasOffender
        ? ComplianceConstants.computeBookingExpiry(occurredAt)
        : null;

    return Incident(
      id: id,
      title: title,
      category: category,
      severity: severity,
      address: address,
      placeName: placeName,
      placeType: placeType,
      geo: GeoCoordinate(
        latitude: lat,
        longitude: lng,
        geohash: GeohashUtil.encode(lat, lng, precision: 8),
      ),
      citySlug: citySlug,
      cityName: cityName,
      stateCode: stateCode,
      occurredAt: occurredAt,
      streetViewUrl: AppEnv.buildStreetViewUrl(latitude: lat, longitude: lng),
      sourceAgency: sourceAgency,
      allegedOffender: hasOffender
          ? AllegedOffender(
              name: offenderName,
              bookingPhotoUrl: null,
              charges: charges,
              bookingDate: occurredAt,
              sourceAgency: bookingAgency ?? sourceAgency,
              disclaimer: ComplianceConstants.presumedInnocentDisclaimer,
              expiresAt: expiry!,
            )
          : null,
      expireAt: expiry,
    );
  }

